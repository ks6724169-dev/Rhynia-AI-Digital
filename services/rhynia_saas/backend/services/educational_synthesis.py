class EducationalSynthesisEngine:
    """Generates structured educational content when LLM streams are empty or rate-limited."""

    @staticmethod
    def synthesize_topic(query: str) -> Optional[str]:
        low = query.lower()
        if any(k in low for k in ["photo", "prakash", "प्रकाश", "पादप"]):
            return EDUCATIONAL_KNOWLEDGE_BASE["photosynthesis"]
        if any(k in low for k in ["plant cell", "पादप कोशिका"]):
            return EDUCATIONAL_KNOWLEDGE_BASE["plant cell"]
        if any(k in low for k in ["animal cell", "जंतु कोशिका"]):
            return EDUCATIONAL_KNOWLEDGE_BASE["animal cell"]
        if any(k in low for k in ["heart", "हृदय", "दिल"]):
            return EDUCATIONAL_KNOWLEDGE_BASE["heart"]
        if any(k in low for k in ["brain", "मस्तिष्क", "दिमाग"]):
            return EDUCATIONAL_KNOWLEDGE_BASE["brain"]
        if any(k in low for k in ["water cycle", "जल चक्र"]):
            return EDUCATIONAL_KNOWLEDGE_BASE["water cycle"]
        if any(k in low for k in ["atom", "परमाणु"]):
            return EDUCATIONAL_KNOWLEDGE_BASE["atom"]
        return None

