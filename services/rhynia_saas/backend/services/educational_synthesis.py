            f"{clean_title} की अवधारणा का क्रमबद्ध और प्रामाणिक शैक्षणिक विवरण:\n\n"
            f"➤ **मुख्य वैज्ञानिक सिद्धांत एवं संकल्पना:**\n"
            f"✔ **परिचय:** इस विषय का मूलभूत परिचय, परिभाषा और सैद्धांतिक आधार।\n"
            f"✔ **आंतरिक संरचना एवं अंगक:** मुख्य घटकों का संरचनात्मक विश्लेषण।\n"
